# binary, hexadecimal, octal, decimal, bool

print(0b00100000)           # binary to decimal
print(chr(0b00101001))      # expressing decimal number '41' in binary '101001'

print(0x41)                 # hexadecimal to decimal
print(0x29)                 # hex value ')' with a decimal value of '41'

print(0o432)                # octal to decimal

print(150)                  # decimal to decimal

a = True + True
print(a)

b = True + False
print(b)

c = False + False
print(c)
