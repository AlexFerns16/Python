# string conversions

stg_1 = 'hello'
stg_2 = 'HELLO'
stg_3 = 'HeLlO'
stg_4 = 'Hello World'
stg_5 = 'hello world'
stg_6 = 'HELLO WORLD'

print()
# upper() > converts string to uppercase

print(stg_1.upper())
print(stg_3.upper())

print()
# lower() > converts string to lowercase

print(stg_2.lower())
print(stg_3.lower())

print()
# capitalize() > converts first character of string to uppercase

print(stg_2.capitalize())
print(stg_1.capitalize())
print(stg_5.capitalize())

print()
# title() > converts first character of each word to uppercase

print(stg_5.title())
print(stg_6.title())

print()
# swapcase() > swap cases in the string

print(stg_3.swapcase())
