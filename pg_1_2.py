# data types
# basic data types
# int, float, str, bool, bytes, complex

print(1)                    # integer > int
print(1.525)                # fraction > float
print(1.5845e2)             # exponential
print(15.845e-1)
print('Python')             # string > str
print(True)                 # boolean > bool
print(3+2j)                 # complex > complex
print(b'\x41\x61')          # bytes > bytes

#   ASCII            Hex            Decimal
#   -----------------------------------------
#   'A' (char)       41 (bytes)     65 (int)
#   'a'              61             97
#   ...
#   refer to the look up table
